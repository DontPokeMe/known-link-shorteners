def decide(domain: str, votes: list[dict], sources: list[str], min_confidence: float,
           min_sources: int) -> dict[str, Any]:
    """Turn per-model votes plus corroboration into accept / reject / review.

    A vote counts for a type only when the model is confident enough. Every
    model that answered must land on the same side, and an accepted domain also
    needs `min_sources` independent upstream lists behind it. Anything else is a
    human decision, not a silent write to a public dataset.
    """
    answered = [v for v in votes if v["category"] != "error"]
    errored = [v for v in votes if v["category"] == "error"]
    if not answered:
        return {"domain": domain, "outcome": "error", "reason": "no model answered",
                "votes": votes, "sources": sources, "type": None}

    buckets = []
    for v in answered:
        entry_type = CATEGORY_TO_TYPE.get(v["category"])
        buckets.append(entry_type if entry_type and v["confidence"] >= min_confidence else None)

    agreed = len(set(buckets)) == 1
    bucket = buckets[0] if agreed else None
    mean_conf = sum(v["confidence"] for v in answered) / len(answered)
    base = {"domain": domain, "votes": votes, "sources": sources,
            "models": [v["model"] for v in answered], "confidence": round(mean_conf, 3)}

    if not agreed:
        disagreement = ", ".join(f"{v['model']}={v['category']}" for v in answered)
        return {**base, "outcome": "review", "type": None,
                "reason": f"models disagree ({disagreement})"}
    if bucket is None:
        return {**base, "outcome": "reject", "type": None,
                "reason": "all models say this is not a shortener/redirector/tracker"}
    if len(sources) < min_sources:
        return {**base, "outcome": "review", "type": bucket,
                "reason": f"classified {bucket} but only {len(sources)} corroborating "
                          f"source(s), need {min_sources}"}
    if errored:
        return {**base, "outcome": "review", "type": bucket,
                "reason": f"{len(errored)} model(s) failed to answer"}
    return {**base, "outcome": "accept", "type": bucket,
            "reason": f"{len(answered)} model(s) agree on {bucket}"}


def make_entry(decision: dict, today: str) -> dict:
    """Build an entry that satisfies schema/shortener.schema.json exactly."""
    domain = decision["domain"]
    sources = decision["sources"]
    models = ", ".join(decision["models"])
    note = (
        f"Auto-ingested: {decision['reason']} (confidence {decision['confidence']:.2f}, "
        f"models: {models}). Pending human review."
    )
    return {
        "domain": domain,
        "type": decision["type"],
        "status": "active",
        "added_at": today,
        "source": "internal",
        # Real provenance when discovery supplied it, the domain itself otherwise.
        "evidence": sources[:5] or [f"https://{domain}/"],
        "notes": note[:500],
    }


def make_inactive_entry(result: CheckResult, original: dict, today: str) -> dict:
    entry = {
        "domain": result.domain,
        "origin": result.origin,
        "last_status": str(result.status),
        "last_checked_at": today,
    }
    for key in ("added_at", "source", "evidence"):
        value = original.get(key)
        if value:
            entry[key] = value
    notes = original.get("notes")
    if notes:
        entry["notes"] = str(notes)[:500]
    elif result.status == "dns_error":
        entry["notes"] = "DNS resolution failed (weekly maintenance)"
    else:
        entry["notes"] = f"HTTP {result.status} (weekly maintenance)"
    return entry


# ------------------------------------------------------------------------ main

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--candidates", type=Path, default=ROOT / "candidates.txt")
    parser.add_argument("--flat", type=Path, default=ROOT / FLAT_FILE,
                        help=f"flat mirror of all active domains (default: {FLAT_FILE})")
    parser.add_argument("--no-flat", action="store_true", help="do not read or write the flat mirror")
    parser.add_argument("--rejected", type=Path, default=ROOT / "candidates.rejected.txt")
    parser.add_argument("--no-check", action="store_true", help="skip the liveness phase")
    parser.add_argument("--no-ollama", action="store_true", help="skip candidate triage")
    parser.add_argument("--dry-run", action="store_true", help="report only, write nothing")
    parser.add_argument("--workers", type=int, default=DEFAULT_WORKERS)
    parser.add_argument("--retry-workers", type=int, default=DEFAULT_RETRY_WORKERS,
                        help="concurrency for the second-chance pass (default: 4)")
    parser.add_argument("--retry-delay", type=float, default=DEFAULT_RETRY_DELAY,
                        help="seconds to wait before the second-chance pass (default: 10)")
    parser.add_argument("--retry-timeout", type=float, default=0,
                        help="timeout for the second-chance pass (default: same as --timeout)")
    parser.add_argument("--no-retry", action="store_true",
                        help="skip the slow re-check of ambiguous results")
    parser.add_argument("--timeout", type=float, default=DEFAULT_TIMEOUT)
    parser.add_argument("--limit", type=int, default=0, help="probe only the first N domains")
    parser.add_argument("--ollama-host", default=DEFAULT_OLLAMA_HOST,
                        help="Ollama base URL (env: OLLAMA_HOST)")
    parser.add_argument("--model", default=DEFAULT_OLLAMA_MODEL,
                        help="force a model (env: OLLAMA_MODEL); default is auto-discovery")
    parser.add_argument("--ollama-workers", type=int, default=DEFAULT_OLLAMA_WORKERS)
    parser.add_argument("--ollama-timeout", type=float, default=120.0)
    parser.add_argument("--min-confidence", type=float, default=DEFAULT_CONFIDENCE)
    parser.add_argument("--consensus", type=int, default=DEFAULT_CONSENSUS,
                        help="how many distinct models must agree before a candidate is "
                             f"auto-accepted (default: {DEFAULT_CONSENSUS})")
    parser.add_argument("--min-sources", type=int, default=DEFAULT_MIN_SOURCES,
                        help="corroborating upstream sources required for auto-accept "
                             f"(default: {DEFAULT_MIN_SOURCES}); others go to the review queue")
    parser.add_argument("--review", type=Path, default=ROOT / "candidates.review.txt",
                        help="queue of candidates needing a human decision")
    parser.add_argument("--no-candidate-probe", action="store_true",
                        help="do not liveness-check candidates before adding them")
    parser.add_argument("--min-params", type=float, default=DEFAULT_MIN_PARAMS,
                        help="prefer models with at least this many billion parameters "
                             f"(default: {DEFAULT_MIN_PARAMS:g}); small models misclassify")
    parser.add_argument("--max-quarantine-pct", type=float, default=DEFAULT_MAX_QUARANTINE_PCT)
    parser.add_argument("--quarantine-on", default="dns,403,404",
                        help="which outcomes quarantine a domain (default: dns,403,404; "
                             "use 'dns' to keep root-404 shorteners such as 1drv.ms)")
    parser.add_argument("--user-agent", default=USER_AGENT,
                        help="override the probe User-Agent")
    parser.add_argument("--report", type=Path, default=DIST / "maintenance-report.json")
    args = parser.parse_args()

    today = date.today().isoformat()
    host = args.ollama_host.rstrip("/")

    global _user_agent
    _user_agent = args.user_agent

    triggers = set()
    for token in args.quarantine_on.split(","):
        token = token.strip().lower()
        if not token:
            continue
        if token not in QUARANTINE_ALIASES:
            parser.error(f"--quarantine-on: unknown value {token!r} (choose from dns, 403, 404)")
        triggers.add(QUARANTINE_ALIASES[token])
    if not triggers and not args.no_check:
        parser.error("--quarantine-on is empty: nothing could ever be quarantined. "
                     "Use --no-check to skip the liveness phase deliberately.")

    active: dict[str, list[dict]] = {name: load_json(DATA / name) for name in ACTIVE_FILES}
    inactive: list[dict] = load_json(DATA / INACTIVE_FILE)
    known: set[str] = {e["domain"] for entries in active.values() for e in entries}
    known_inactive: set[str] = {e["domain"] for e in inactive}

    print(f"Loaded {len(known)} active domains, {len(known_inactive)} inactive.")

    # The flat mirror is regenerated from the JSON, so anything a maintainer
    # hand-added to it would be silently wiped. Adopt those lines instead.
    adopted: list[str] = []
    flat_conflicts: list[str] = []
    flat_aliases: list[str] = []
    if not args.no_flat and args.flat.exists():
        flat_domains = {
            d
            for d in (normalise_domain(ln, strip_www=False) for ln in read_lines(args.flat))
            if d
        }
        for domain in sorted(flat_domains - known):
            if domain in known_inactive:
                flat_conflicts.append(domain)
                continue
            # www.shrunken.com and shrunken.com are the same site: adopting the
            # other spelling would silently create a paired duplicate entry that
            # no validator can catch.
            alias = domain[4:] if domain.startswith("www.") else f"www.{domain}"
            if alias in known:
                flat_aliases.append(f"{domain} (already present as {alias})")
                continue
            if alias in known_inactive:
                flat_conflicts.append(domain)
                continue
            active["shorteners.json"].append({
                "domain": domain,
                "type": "shortener",
                "status": "active",
                "added_at": today,
                "source": "internal",
                "evidence": [f"https://{domain}/"],
                "notes": f"Adopted from {args.flat.name} (hand-added); pending human review.",
            })
            known.add(domain)
            adopted.append(domain)
        if adopted:
            print(f"Adopted {len(adopted)} hand-added domain(s) from {args.flat.name}.")
        if flat_conflicts:
            print(f"Ignored {len(flat_conflicts)} {args.flat.name} line(s) already quarantined in {INACTIVE_FILE}.")
        if flat_aliases:
            print(f"Ignored {len(flat_aliases)} {args.flat.name} line(s) duplicating an existing entry.")
    report_flat = {
        "adopted": adopted,
        "ignored_inactive": flat_conflicts,
        "ignored_alias": flat_aliases,
    }

    report: dict[str, Any] = {
        "run_at": datetime.now(timezone.utc).isoformat(),
        "date": today,
        "dry_run": args.dry_run,
    }

    # ---------------------------------------------------------- phase 1: clean
    quarantined: list[dict] = []
    check_results: list[CheckResult] = []
    quarantine_skipped = False

    if args.no_check:
        print("\n[1/3] Liveness check skipped (--no-check).")
    else:
        targets = [
            (e["domain"], e.get("type", "shortener"))
            for name in ACTIVE_FILES
            for e in active[name]
        ]
        targets.sort()
        if args.limit:
            targets = targets[: args.limit]
        print(f"\n[1/3] Liveness check: {len(targets)} domains, {args.workers} workers, {args.timeout}s timeout.")
        check_results = run_liveness(targets, args.workers, args.timeout)

        # Second chance: a 429 means "come back later", and a timeout under
        # load is not evidence of anything. Re-check slowly before reporting.
        retry_stats = {"attempted": 0, "recovered": 0}
        if not args.no_retry:
            retry_targets = [(r.domain, r.origin) for r in check_results if r.verdict == "review"]
            if retry_targets:
                retry_timeout = args.retry_timeout or args.timeout
                if args.retry_delay > 0:
                    print(f"  waiting {args.retry_delay:.0f}s before re-checking "
                          f"{len(retry_targets)} ambiguous result(s)")
                    time.sleep(args.retry_delay)
                print(f"  re-checking {len(retry_targets)} ambiguous result(s) at "
                      f"{args.retry_workers} workers, {retry_timeout}s timeout")
                retried = {
                    r.domain: r
                    for r in run_liveness(retry_targets, args.retry_workers, retry_timeout)
                }
                merged: list[CheckResult] = []
                for r in check_results:
                    replacement = retried.get(r.domain) if r.verdict == "review" else None
                    if replacement is None:
                        merged.append(r)
                        continue
                    if replacement.verdict != "review":
                        retry_stats["recovered"] += 1
                    merged.append(replacement)
                check_results = merged
                retry_stats["attempted"] = len(retry_targets)
                print(f"  recovered {retry_stats['recovered']}/{len(retry_targets)} on retry")

        # A "dead" outcome the maintainer has excluded is downgraded to review,
        # never silently dropped.
        for r in check_results:
            if r.verdict == "dead" and str(r.status) not in triggers:
                r.verdict = "review"
                r.message = f"{r.status} excluded by --quarantine-on"
        dead = [r for r in check_results if r.verdict == "dead" and str(r.status) in QUARANTINE_STATUSES]

        # Circuit breaker: a runner-side network failure must never be able to
        # delete a large slice of the dataset in one unattended commit.
        cap = max(QUARANTINE_FLOOR, int(len(check_results) * args.max_quarantine_pct / 100))
        if len(dead) > cap:
            quarantine_skipped = True
            print(
                f"  !! {len(dead)} domains look dead, above the safety cap of {cap} "
                f"({args.max_quarantine_pct}%). Refusing to quarantine; inspect the report.",
                file=sys.stderr,
            )
            # Downgrade rather than drop: these are precisely the domains the
            # warning tells a human to go and look at, so they must stay in the
            # review counts and in the workflow's review table.
            for r in dead:
                r.verdict = "review"
                r.message = f"{r.status}: suppressed by the {cap}-domain safety cap"
            dead = []

        alive_count = sum(1 for r in check_results if r.verdict == "alive")
        review = [r for r in check_results if r.verdict == "review"]

        by_domain = {e["domain"]: e for entries in active.values() for e in entries}
        dead_domains = {r.domain for r in dead}
        for r in dead:
            quarantined.append(make_inactive_entry(r, by_domain.get(r.domain, {}), today))
        if dead_domains:
            for name in ACTIVE_FILES:
                active[name] = [e for e in active[name] if e["domain"] not in dead_domains]

        print(
            f"  alive: {alive_count} | dead: {len(dead_domains)} | needs review: {len(review)}"
        )
        report["liveness"] = {
            "checked": len(check_results),
            "alive": alive_count,
            "quarantined": len(dead_domains),
            "review": len(review),
            "quarantine_cap": cap,
            "quarantine_on": sorted(triggers),
            "retry": retry_stats,
            "user_agent": args.user_agent,
            "quarantine_skipped": quarantine_skipped,
            "results": [asdict(r) for r in check_results],
        }

    # --------------------------------------------------------- phase 2: ingest
    accepted: list[dict] = []
    rejected: list[str] = []
    review_queue: list[tuple[str, list[str], str]] = []   # (domain, sources, reason)
    decisions: list[dict] = []
    models: list[str] = []

    raw_lines = read_lines(args.candidates)
    seen_candidates: set[str] = set()
    pending: dict[str, list[str]] = {}          # domain -> corroborating sources
    skipped_known: list[str] = []
    unparseable: list[str] = []

    for line in raw_lines:
        parsed = parse_candidate_line(line)
        if parsed is None:
            continue                            # blank or comment
        raw_domain, sources = parsed
        domain = normalise_domain(raw_domain)
        if domain is None:
            unparseable.append(line)
            continue
        if domain in seen_candidates:
            # Same domain queued twice: union the provenance rather than drop it.
            pending.setdefault(domain, [])
            pending[domain] = sorted(set(pending[domain]) | set(sources))
            continue
        seen_candidates.add(domain)
        alias = domain[4:] if domain.startswith("www.") else f"www.{domain}"
        if domain in known or domain in known_inactive or alias in known or alias in known_inactive:
            skipped_known.append(domain)
            continue
        pending[domain] = sorted(set(sources))

    pending_domains = sorted(pending)

    if args.no_ollama:
        print(f"\n[2/3] Candidate triage skipped (--no-ollama). {len(pending_domains)} candidate(s) left in place.")
    elif not args.candidates.exists():
        print(f"\n[2/3] No {args.candidates.name} found; nothing to ingest.")
    elif not pending_domains:
        print(f"\n[2/3] No new candidates ({len(skipped_known)} already known, {len(unparseable)} unparseable).")
    else:
        print(f"\n[2/3] Candidate triage: {len(pending_domains)} new domain(s) via Ollama at {host}.")
        models = select_models(host, args.model, args.min_params, args.consensus)
        if models:
            print(f"  voting models ({len(models)}): {', '.join(models)}")
            if len(models) < args.consensus:
                print(f"  only {len(models)} usable model(s) installed; "
                      f"consensus of {args.consensus} requested.")
            votes = run_triage(pending_domains, host, models, args.ollama_workers, args.ollama_timeout)

            # A candidate that does not resolve is not worth adding, whatever
            # the models think of the name.
            liveness: dict[str, CheckResult] = {}
            if not args.no_candidate_probe:
                print(f"  probing {len(pending_domains)} candidate(s) for liveness")
                liveness = {
                    r.domain: r
                    for r in run_liveness([(d, "shortener") for d in pending_domains],
                                          min(args.workers, 8), args.timeout)
                }

            for domain in pending_domains:
                sources = pending[domain]
                decision = decide(domain, votes[domain], sources,
                                  args.min_confidence, args.min_sources)
                probe = liveness.get(domain)
                if decision["outcome"] == "accept" and probe is not None:
                    if probe.verdict == "dead":
                        decision = {**decision, "outcome": "reject",
                                    "reason": f"classified {decision['type']} but the domain is "
                                              f"dead ({probe.status})"}
                    elif probe.verdict == "review":
                        decision = {**decision, "outcome": "review",
                                    "reason": f"classified {decision['type']} but liveness is "
                                              f"inconclusive ({probe.status})"}
                decision["liveness"] = str(probe.status) if probe else None
                decisions.append(decision)

                if decision["outcome"] == "accept":
                    entry = make_entry(decision, today)
                    accepted.append(entry)
                    active[FILE_FOR_TYPE[decision["type"]]].append(entry)
                    known.add(domain)
                elif decision["outcome"] == "reject":
                    rejected.append(domain)
                elif decision["outcome"] == "review":
                    review_queue.append((domain, sources, decision["reason"]))
                # "error" outcomes stay in candidates.txt and are retried next run

            for d in decisions:
                icon = {"accept": "+", "reject": "-", "review": "?", "error": "!"}[d["outcome"]]
                print(f"  {icon} {d['domain']}: {d['reason']}")
            print(f"  accepted: {len(accepted)} | rejected: {len(rejected)} | "
                  f"needs review: {len(review_queue)}")

    report["ingest"] = {
        "candidate_lines": len(raw_lines),
        "new_candidates": len(pending_domains),
        "already_known": len(skipped_known),
        "unparseable": unparseable,
        "models": models,
        "consensus_required": args.consensus,
        "min_sources": args.min_sources,
        "accepted": [e["domain"] for e in accepted],
        "rejected": rejected,
        "review_queue": [{"domain": d, "sources": src, "reason": why} for d, src, why in review_queue],
        "decisions": decisions,
    }

    # ------------------------------------------------- phase 3: dedupe and sort
    print("\n[3/3] Deduplicating and sorting.")
    seen_global: set[str] = set()
    duplicates: list[str] = []
    for name in ACTIVE_FILES:
        unique: list[dict] = []
        for entry in active[name]:
            domain = entry.get("domain")
            if not domain or domain in seen_global:
                duplicates.append(domain or "<missing>")
                continue
            seen_global.add(domain)
            unique.append(entry)
        unique.sort(key=lambda e: e["domain"])
        active[name] = unique

    merged_inactive = {e["domain"]: e for e in inactive}
    for entry in quarantined:
        merged_inactive[entry["domain"]] = entry
    # A domain must never appear in both an active file and inactive.json.
    inactive_out = sorted(
        (e for d, e in merged_inactive.items() if d not in seen_global),
        key=lambda e: e["domain"],
    )

    print(f"  active: {sum(len(v) for v in active.values())} | inactive: {len(inactive_out)} | duplicates dropped: {len(duplicates)}")
    report["normalise"] = {
        "shorteners": len(active["shorteners.json"]),
        "redirectors": len(active["redirectors.json"]),
        "tracking": len(active["tracking.json"]),
        "inactive": len(inactive_out),
        "duplicates_dropped": duplicates,
    }
    report["flat_mirror"] = report_flat

    # ------------------------------------------------------------------- write
    # The report is diagnostic output, not dataset state: always write it, so a
    # dry run can actually be inspected.
    save_json(args.report, report)

    if args.dry_run:
        print(f"\nDry run: no dataset changes written. Report: {rel(args.report)}")
    else:
        for name in ACTIVE_FILES:
            save_json(DATA / name, active[name])
        save_json(DATA / INACTIVE_FILE, inactive_out)

        if not args.no_flat:
            # Record what we deliberately did not adopt, so the maintainer sees
            # it in the file rather than only in one line of run log.
            notes = [f"# not adopted ({INACTIVE_FILE} has it): {d}" for d in flat_conflicts]
            notes += [f"# not adopted ({d})" for d in flat_aliases]
            write_lines(args.flat, FLAT_HEADER[:-1] + notes + [""], sorted(seen_global))

        # candidates.txt is an inbox: drop what we have decided on, keep the
        # rest (errors, or everything if Ollama was unavailable) for next run.
        if args.candidates.exists():
            decided = ({e["domain"] for e in accepted} | set(rejected)
                       | set(skipped_known) | {d for d, _, _ in review_queue})
            remaining = [format_candidate_line(d, pending[d])
                         for d in pending_domains if d not in decided]
            # Never silently drop a line we could not parse -- it is more likely
            # a typo the maintainer wants to fix than something to discard. A
            # previous run's "# unparseable:" line comes back as a comment, so
            # preserving comments is what keeps it alive across runs.
            remaining += [f"# unparseable: {line}" for line in unparseable]
            preserved = [ln for ln in raw_lines if ln.startswith("#")]
            write_lines(args.candidates, preserved + [""] if preserved else CANDIDATES_HEADER, remaining)
        # The review queue is what a human (or the workflow's PR) acts on. It is
        # rewritten whole each run: anything a maintainer moves back into
        # candidates.txt simply stops reappearing here.
        if review_queue or args.review.exists():
            existing: dict[str, str] = {}
            for ln in read_lines(args.review):
                parsed = parse_candidate_line(ln)
                if parsed:
                    existing[parsed[0]] = ln
            lines = []
            for domain, sources, why in sorted(review_queue):
                lines.append(f"# {why}")
                lines.append(format_candidate_line(domain, sources))
            # Keep entries queued by earlier runs that this run did not re-decide.
            carried = [ln for d, ln in sorted(existing.items())
                       if d not in {x for x, _, _ in review_queue} and d not in known
                       and d not in known_inactive]
            if carried:
                lines.append("")
                lines.extend(carried)
            write_lines(
                args.review,
                [
                    "# Candidates needing a human decision: the models disagreed, the",
                    "# corroboration was too thin, or liveness was inconclusive.",
                    "# To accept one, move its line into candidates.txt and delete it here.",
                    "",
                ],
                lines,
            )

        if rejected:
            previous = [
                ln for ln in read_lines(args.rejected) if ln and not ln.startswith("#")
            ]
            write_lines(
                args.rejected,
                [
                    "# Domains Ollama judged not to be shorteners/redirectors/trackers.",
                    "# Kept so they are not re-evaluated every week. Delete a line to retry it.",
                    "",
                ],
                sorted(set(previous) | set(rejected)),
            )
        written = ["data/*.json"]
        if review_queue:
            written.append(args.review.name)
        if not args.no_flat:
            written.append(args.flat.name)
        written.append(rel(args.report))
        print(f"\nWrote {', '.join(written)}")

    # ----------------------------------------------------------------- summary
    print("\n--- Summary ---")
    if not args.no_check:
        lv = report["liveness"]
        print(f"Checked {lv['checked']} | alive {lv['alive']} | quarantined {lv['quarantined']} | review {lv['review']}")
    print(f"Candidates: {len(pending_domains)} new | accepted {len(accepted)} | "
          f"rejected {len(rejected)} | needs review {len(review_queue)}")
    print(f"Dataset: {report['normalise']['shorteners']} shorteners, "
          f"{report['normalise']['redirectors']} redirectors, "
          f"{report['normalise']['tracking']} tracking, "
          f"{report['normalise']['inactive']} inactive")

    if quarantine_skipped:
        print("\nSafety cap tripped: nothing was quarantined. Review the report before rerunning.", file=sys.stderr)
        return EXIT_QUARANTINE_CAP
    return 0


if __name__ == "__main__":
    sys.exit(main())
