#!/usr/bin/env python3
"""
Weekly maintenance for the known-link-shorteners datasets.

Three phases, each independently switchable:

  1. Clean    -- concurrent HEAD (GET fallback) liveness check of every active
                 domain. Domains that return a confirmed 403/404 or fail DNS
                 resolution are quarantined into data/inactive.json. Everything
                 else is kept; ambiguous results are reported, never removed.
  2. Ingest   -- reads candidates.txt, normalises each line to a bare domain,
                 drops anything already known, and asks a local Ollama model
                 (auto-discovered via /api/tags) whether the domain is a
                 shortener / link-in-bio / redirector / tracker or an ordinary
                 site. Accepted candidates become schema-valid entries.
  3. Normalise-- merges, deduplicates (across all four data files), sorts by
                 domain and rewrites every file in the repo's canonical format,
                 plus the flat mirror shorteners.txt.

shorteners.txt is the flat, human-readable list of every active domain: it is
read at the start of a run (hand-added lines are adopted into the dataset) and
regenerated at the end. data/*.json remains the source of truth, so output
still conforms to schema/shortener.schema.json and schema/inactive.schema.json
and `python scripts/validate_data.py` / `npm run ci` both keep passing.

Usage:
  python3 scripts/maintain_shorteners.py                 # full run
  python3 scripts/maintain_shorteners.py --dry-run       # change nothing
  python3 scripts/maintain_shorteners.py --no-check      # ingest only
  python3 scripts/maintain_shorteners.py --no-ollama     # liveness only
  python3 scripts/maintain_shorteners.py --limit 50      # probe a sample
"""
