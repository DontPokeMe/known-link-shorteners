def parse_candidate_line(line: str) -> tuple[str, list[str]] | None:
    """Split a candidates.txt line into (raw_domain, source_urls).

    Discovery writes provenance inline as `example.com  # src=https://a,https://b`
    so a queued domain carries the evidence that justified queueing it.
    """
    if not line or line.lstrip().startswith("#"):
        return None
    domain_part, _, comment = line.partition("#")
    domain_part = domain_part.strip()
    if not domain_part:
        return None
    sources: list[str] = []
    marker = comment.strip()
    if marker.startswith("src="):
        sources = [u.strip() for u in marker[4:].split(",") if u.strip().startswith(("http://", "https://"))]
    return domain_part, sources


def format_candidate_line(domain: str, sources: list[str]) -> str:
    return f"{domain}  # src={','.join(sources)}" if sources else domain


def normalise_domain(raw: str, strip_www: bool = True) -> str | None:
    """Turn a pasted URL or hostname into a bare, schema-valid domain.

    strip_www is off when re-reading our own canonical output: the dataset does
    contain www-prefixed entries (www.shrunken.com), and rewriting those on a
    round-trip would make the flat mirror non-idempotent.
    """
    value = raw.strip().strip('"\'<>,;')
    if not value or value.startswith("#"):
        return None
    value = re.sub(r"^[a-z][a-z0-9+.-]*://", "", value, flags=re.IGNORECASE)
    value = value.split("/")[0].split("?")[0].split("#")[0]
    value = value.split("@")[-1]          # strip user:pass@
    value = value.split(":")[0]           # strip :port
    value = value.strip().rstrip(".").lower()
    # No dataset entry is www-prefixed; www.nytimes.com and nytimes.com are the
    # same site, and candidates pasted from articles routinely carry the prefix.
    if strip_www and value.startswith("www.") and value.count(".") > 1:
        value = value[4:]
    if not value or "." not in value:
        return None
    if not value.isascii():
        try:
            value = value.encode("idna").decode("ascii")
        except (UnicodeError, ValueError):
            return None
    return value if DOMAIN_RE.match(value) else None


# ------------------------------------------------------------------ liveness

@dataclass
class CheckResult:
    domain: str
    origin: str
    verdict: str            # "alive" | "dead" | "review"
    status: int | str
    scheme: str
    method: str
    message: str | None = None


_local = threading.local()
_user_agent = USER_AGENT


def get_session() -> requests.Session:
    session = getattr(_local, "session", None)
    if session is None:
        session = requests.Session()
        session.headers.update({**DEFAULT_HEADERS, "User-Agent": _user_agent})
        # Our own scheme/method fallback is the retry strategy; only let
        # urllib3 retry the cheap connect-level failures.
        adapter = HTTPAdapter(
            pool_connections=16,
            pool_maxsize=16,
            max_retries=Retry(total=1, connect=1, read=0, status=0, backoff_factor=0.3),
        )
        session.mount("https://", adapter)
        session.mount("http://", adapter)
        _local.session = session
    return session


def _request(method: str, url: str, timeout: float) -> requests.Response:
    return get_session().request(
        method, url, timeout=timeout, allow_redirects=False, stream=(method == "GET")
    )


def check_domain(domain: str, origin: str, timeout: float) -> CheckResult:
    """HEAD first (cheap), GET as fallback and as confirmation of a 403/404."""
    last: CheckResult | None = None
    for scheme in ("https", "http"):
        url = f"{scheme}://{domain}/"
        try:
            resp = _request("HEAD", url, timeout)
            status, method = resp.status_code, "HEAD"

            # Plenty of hosts mishandle HEAD -- confirm anything that looks
            # negative with a real GET before acting on it.
            if status in (400, 403, 404, 405, 501) or status >= 500:
                confirmed = False
                try:
                    resp = _request("GET", url, timeout)
                    resp.close()
                    status, method = resp.status_code, "GET"
                    confirmed = True
                except requests.RequestException:
                    pass
                if status in (403, 404) and not confirmed:
                    # HEAD said 403/404 but the confirming GET never landed --
                    # that is single-method evidence, not proof the host is dead.
                    last = CheckResult(domain, origin, "review", status, scheme, "HEAD",
                                       "403/404 on HEAD, confirming GET failed")
                    continue

            if status in (403, 404):
                # Confirmed by GET (or HEAD-only if GET failed): quarantine.
                return CheckResult(domain, origin, "dead", str(status), scheme, method)
            if 200 <= status < 400:
                return CheckResult(domain, origin, "alive", status, scheme, method)
            last = CheckResult(
                domain, origin, "review", status, scheme, method, "unexpected status"
            )
        except requests.exceptions.SSLError as e:
            last = CheckResult(domain, origin, "review", "tls_error", scheme, "HEAD", str(e)[:200])
            continue  # retry over http://
        except requests.exceptions.Timeout:
            last = CheckResult(domain, origin, "review", "timeout", scheme, "HEAD", "timed out")
            continue
        except requests.exceptions.ConnectionError as e:
            err = str(e).lower()
            if any(marker in err for marker in DNS_MARKERS):
                # DNS is scheme independent -- no point trying http://.
                return CheckResult(domain, origin, "dead", "dns_error", scheme, "HEAD", err[:200])
            last = CheckResult(domain, origin, "review", "connect_error", scheme, "HEAD", str(e)[:200])
            continue
        except Exception as e:  # noqa: BLE001 - never let one domain kill the run
            last = CheckResult(domain, origin, "review", "error", scheme, "HEAD", str(e)[:200])
            continue
    return last or CheckResult(domain, origin, "review", "error", "https", "HEAD", "no result")


def run_liveness(targets: list[tuple[str, str]], workers: int, timeout: float) -> list[CheckResult]:
    results: list[CheckResult] = []
    if not targets:
        return results
    done = 0
    with ThreadPoolExecutor(max_workers=workers) as pool:
        futures = {pool.submit(check_domain, d, o, timeout): (d, o) for d, o in targets}
        for fut in as_completed(futures):
            domain, origin = futures[fut]
            try:
                results.append(fut.result())
            except Exception as e:  # noqa: BLE001
                results.append(
                    CheckResult(domain, origin, "review", "error", "", "", str(e)[:200])
                )
            done += 1
            if done % 100 == 0 or done == len(targets):
                print(f"  checked {done}/{len(targets)}", flush=True)
    return results


# -------------------------------------------------------------------- Ollama

def list_models(host: str) -> list[tuple[str, float]]:
    """Installed models as (name, parameter_count_in_billions)."""
    r = requests.get(f"{host}/api/tags", timeout=5)
    r.raise_for_status()
    out: list[tuple[str, float]] = []
    for m in r.json().get("models", []):
        name = m.get("name")
        if not name:
            continue
        raw = str((m.get("details") or {}).get("parameter_size") or "").strip().upper()
        try:
            params = float(raw.rstrip("B")) if raw.endswith("B") else 0.0
        except ValueError:
            params = 0.0
        out.append((name, params))
    return sorted(out)


def resolve_model(host: str, requested: str | None, min_params: float) -> str | None:
    """Pick an installed model. Never fail over a missing hardcoded tag.

    Order: explicit request -> a preferred family (qwen2.5, llama3.2, mistral)
    at or above min_params -> the largest general-purpose model at or above
    min_params -> a preferred family at any size -> the largest model installed.

    The size floor is not arbitrary: measured against a 10-domain set on this
    task, llama3.2:3b scored 6/10 and called zapier.com, notion.so and
    vercel.app shorteners, while llama3.1:8b and phi4 both scored 9/10. A
    false positive here writes a wrong entry into a public dataset.
    """
    try:
        installed = list_models(host)
    except Exception as e:  # noqa: BLE001
        print(f"  Ollama unreachable at {host} ({e}); skipping candidate triage.")
        return None

    if not installed:
        print(f"  Ollama at {host} has no models installed (try: ollama pull qwen2.5).")
        return None
    print("  installed models: " + ", ".join(f"{n} ({p:g}B)" if p else n for n, p in installed))

    def exact(name: str, want: str) -> bool:
        """qwen2.5-coder must NOT satisfy a preference for qwen2.5."""
        return name.lower() == want.lower() or name.split(":")[0].lower() == want.lower()

    if requested:
        for name, _ in installed:
            if exact(name, requested) or name.split(":")[0].lower().startswith(requested.lower()):
                return name
        print(f"  requested model {requested!r} is not installed; falling back to discovery.")

    usable = [(n, p) for n, p in installed if not any(x in n.lower() for x in MODEL_EXCLUDE)]
    general = [(n, p) for n, p in usable if not any(x in n.lower() for x in MODEL_DEPRIORITISE)]
    biggest = sorted(general or usable, key=lambda t: t[1], reverse=True)

    for want in MODEL_PREFERENCE:
        for name, params in general:
            if exact(name, want) and params >= min_params:
                return name
    for name, params in biggest:
        if params >= min_params:
            print(f"  no preferred family at >={min_params:g}B; using the largest installed ({name}, {params:g}B).")
            return name
    for want in MODEL_PREFERENCE:
        for name, _ in general:
            if exact(name, want):
                print(f"  nothing at >={min_params:g}B installed; falling back to {name} "
                      "-- review auto-ingested entries closely.")
                return name
    if biggest:
        name = biggest[0][0]
        print(f"  no preferred model installed; falling back to {name}.")
        return name
    return None


def select_models(host: str, requested: str | None, min_params: float, count: int) -> list[str]:
    """Pick up to `count` distinct models to vote on each candidate.

    One 7B-class model scores about 9/10 on this task; requiring two independent
    models to agree is what turns that into an auto-accept gate a public dataset
    can live with. Falls back to however many are installed.
    """
    chosen: list[str] = []
    first = resolve_model(host, requested, min_params)
    if not first:
        return []
    chosen.append(first)
    if count <= 1:
        return chosen
    try:
        installed = list_models(host)
    except Exception:  # noqa: BLE001
        return chosen
    usable = [
        (n, pr) for n, pr in installed
        if not any(x in n.lower() for x in MODEL_EXCLUDE)
        and not any(x in n.lower() for x in MODEL_DEPRIORITISE)
        and n not in chosen
    ]
    # Prefer other large models, and prefer a different family for independence.
    def family(name: str) -> str:
        return name.split(":")[0].split("-")[0].lower()

    usable.sort(key=lambda t: (family(t[0]) == family(first), -t[1]))
    for name, params in usable:
        if len(chosen) >= count:
            break
        if params >= min_params:
            chosen.append(name)
    return chosen


def classify_candidate(domain: str, host: str, model: str, timeout: float) -> dict[str, Any]:
    payload = {
        "model": model,
        "prompt": CLASSIFIER_PROMPT.format(domain=domain),
        "stream": False,
        "format": "json",
        "options": {"temperature": 0, "num_predict": 120},
    }
    try:
        r = requests.post(f"{host}/api/generate", json=payload, timeout=timeout)
        r.raise_for_status()
        raw = r.json().get("response", "")
    except Exception as e:  # noqa: BLE001
        return {"domain": domain, "category": "error", "confidence": 0.0, "reason": str(e)[:200]}

    try:
        parsed = json.loads(raw)
    except json.JSONDecodeError:
        match = re.search(r"\{.*\}", raw, re.DOTALL)
        if not match:
            return {"domain": domain, "category": "error", "confidence": 0.0,
                    "reason": f"unparseable response: {raw[:120]}"}
        try:
            parsed = json.loads(match.group(0))
        except json.JSONDecodeError:
            return {"domain": domain, "category": "error", "confidence": 0.0,
                    "reason": f"unparseable response: {raw[:120]}"}

    category = str(parsed.get("category", "other")).strip().lower().replace("-", "_").replace(" ", "_")
    if category not in CATEGORY_TO_TYPE and category != "other":
        category = "other"
    try:
        confidence = max(0.0, min(1.0, float(parsed.get("confidence", 0.0))))
    except (TypeError, ValueError):
        confidence = 0.0
    return {
        "domain": domain,
        "category": category,
        "confidence": confidence,
        "reason": str(parsed.get("reason", ""))[:200],
    }


def run_triage(domains: list[str], host: str, models: list[str], workers: int,
               timeout: float) -> dict[str, list[dict]]:
    """Every model votes on every domain. Returns {domain: [vote, ...]}."""
    jobs = [(d, m) for d in domains for m in models]
    votes: dict[str, list[dict]] = {d: [] for d in domains}
    with ThreadPoolExecutor(max_workers=workers) as pool:
        futures = {
            pool.submit(classify_candidate, d, host, m, timeout): (d, m) for d, m in jobs
        }
        for fut in as_completed(futures):
            domain, model = futures[fut]
            try:
                verdict = fut.result()
            except Exception as e:  # noqa: BLE001
                verdict = {"domain": domain, "category": "error", "confidence": 0.0,
                           "reason": str(e)[:200]}
            verdict["model"] = model
            votes[domain].append(verdict)
    for vs in votes.values():
        vs.sort(key=lambda v: v["model"])
    return votes


